/**
  * @brief  LED blinking pattern.
  * It relies on the global variables:
  * - blinking_scheme (BLINKING_SCHEME_MAX)
  * - blink_period (ms)
  * - light_on (bool)
  * @param  None
  * @retval None
  */
void Execute_Blink_Scheme(void)
{
  uint16_t pin = 0;

  if (!light_on) {
    return;
  }

  switch(blinking_scheme) {
    case 0: /* SCHEME 0: All Blink Together */
      HAL_GPIO_WritePin(LED_GPIO_Port, Green_LED_Pin |
                                        Red_LED_Pin |
                                        Orange_LED_Pin |
                                        Blue_LED_Pin, GPIO_PIN_SET);
      HAL_Delay(blink_period);

      HAL_GPIO_WritePin(LED_GPIO_Port, Green_LED_Pin |
                                        Red_LED_Pin |
                                        Orange_LED_Pin |
                                        Blue_LED_Pin, GPIO_PIN_RESET);
      HAL_Delay(blink_period);

      break;

    case 1: /* SCHEME 1: Rotating */
      for(pin = 0; pin < ARRAY_SIZE(led_array); pin++) {
        HAL_GPIO_WritePin(LED_GPIO_Port, led_array[pin], GPIO_PIN_SET);

        HAL_Delay(blink_period);

        HAL_GPIO_WritePin(LED_GPIO_Port, led_array[pin], GPIO_PIN_RESET);
      }

      break;

    case 2: /* SCHEME 2: Diagonal Flip-Flop */
      HAL_GPIO_WritePin(LED_GPIO_Port, Green_LED_Pin |
                                       Red_LED_Pin, GPIO_PIN_SET);
      HAL_GPIO_WritePin(LED_GPIO_Port, Orange_LED_Pin |
                                       Blue_LED_Pin, GPIO_PIN_RESET);
      HAL_Delay(blink_period);

      HAL_GPIO_WritePin(LED_GPIO_Port, Green_LED_Pin |
                                       Red_LED_Pin, GPIO_PIN_RESET);
      HAL_GPIO_WritePin(LED_GPIO_Port, Orange_LED_Pin |
                                       Blue_LED_Pin, GPIO_PIN_SET);
      HAL_Delay(blink_period);

      break;

    case 3: /* SCHEME 3: Filling Up Circle */
      for(pin = 0; pin < ARRAY_SIZE(led_array); pin++) {
        HAL_GPIO_WritePin(LED_GPIO_Port, led_array[pin], GPIO_PIN_SET);

        HAL_Delay(blink_period);
      }

      /* Clear all */
      LEDs_Off();

      HAL_Delay(blink_period);

      break;
  }
}

/**
  * @brief  EXTI Line Detection Callback.
  * This function is automatically called when ANY configured GPIO interrupt occurs.
  * @param  GPIO_Pin: The specific pin that triggered the interrupt.
  */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  switch(GPIO_Pin) {
    case SW3_Pin: /* Speed Up */
      if (blink_period > BLINK_PERIOD_MS_MIN) {
        blink_period -= BLINK_PERIOD_MS_SUB;
      }

      break;

    case SW4_Pin: /* Slow Down */
      if (blink_period < BLINK_PERIOD_MS_MAX) {
        blink_period += BLINK_PERIOD_MS_SUB;
      }

      break;

    case SW0_Pin: /* Next Scheme */
      blinking_scheme++;
      if(blinking_scheme > BLINKING_SCHEME_MAX) {
        blinking_scheme = BLINKING_SCHEME_MIN;
      }

      break;

    case SW2_Pin: /* Previous Scheme */
      if(BLINKING_SCHEME_MIN == blinking_scheme) {
        blinking_scheme = BLINKING_SCHEME_MAX;
      } else {
        blinking_scheme--;
      }

      break;

    case SW1_Pin: /* ON/OFF */
      light_on = !light_on;

      break;

    default:
      break;
  }
}

